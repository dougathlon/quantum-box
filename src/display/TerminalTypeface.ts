export function terminalTextWidth(
  text: string,
  pixel = 1,
  spacing = pixel,
): number {
  return Math.max(
    0,
    [...text].reduce(
      (sum, c) =>
        sum +
        (TERMINAL_GLYPHS[c] ?? TERMINAL_GLYPHS["?"]!).split("/")[0]!.length *
          pixel +
        spacing,
      0,
    ) - spacing,
  );
}
export function terminalGlyphRects(text: string, x = 0, y = 0) {
  const result: Array<{
    x: number;
    y: number;
    width: number;
    height: number;
  }> = [];
  for (const character of text) {
    const rows = (TERMINAL_GLYPHS[character] ?? TERMINAL_GLYPHS["?"]!).split(
      "/",
    );

    const width = rows[0]!.length;
    const ink = (dx: number, dy: number) => rows[dy]?.[dx] === "1";
    // Refine diagonal corners on a doubled grid while retaining C's metrics.
    // Each source cell becomes four independently chosen binary pixels.
    for (let dy = 0; dy < 7; dy++) {
      for (let dx = 0; dx < width; dx++) {
        const center = ink(dx, dy);
        const up = ink(dx, dy - 1),
          down = ink(dx, dy + 1);
        const left = ink(dx - 1, dy),
          right = ink(dx + 1, dy);
        const corners =
          up !== down && left !== right
            ? [
                left === up ? left : center,
                up === right ? right : center,
                left === down ? left : center,
                down === right ? right : center,
              ]
            : [center, center, center, center];
        corners.forEach((filled, i) => {
          // D needs square stem terminals; rounding these makes it read as O.
          if (
            filled ||
            ((character === "D" || character === "B") && dx === 0) ||
            (character === "5" && center && (dy === 0 || (dx === 0 && dy < 3)))
          )
            result.push({
              x: x + dx + (i % 2) / 2,
              y: y + dy + Math.floor(i / 2) / 2,
              width: 0.5,
              height: 0.5,
            });
        });
      }
    }
    x += width + 1;
  }
  return result;
}
